export const i18n = $state<{ lang: Lang }>({ lang: load<Lang>('remybun.lang', 'ro') })

export function setLang(lang: Lang) {
  i18n.lang = lang
  save('remybun.lang', lang)
  document.documentElement.lang = lang
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const text = dictionaries[i18n.lang][key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

/** Translates a server error reason; unknown reasons fall back to a generic message. */
export function errorText(reason: string): string {
  const key = `errors.${reason.split(':')[0]}` as Key
  return key in ro ? t(key) : t('errors.error')
}
